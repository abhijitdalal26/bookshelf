# Renders each book's first PDF page as its cover (app/covers/*.jpg) and writes app/covers.js:
#   window.COVERS = { "<book path>": { f: "covers/<id>.jpg", ar: width/height, bg: "#rrggbb", fg: "#rrggbb" } }
# bg is sampled from the cover's left edge so the spine on the shelf matches the real book.
# Run after scan-books.js:  python scripts/make-covers.py   (needs PyMuPDF: pip install pymupdf)
# Existing covers are kept; pass --force to redo them all.

import hashlib, json, os, re, sys
import fitz  # PyMuPDF

ROOT = os.path.join(os.path.dirname(__file__), "..")
APP = os.path.join(ROOT, "app")
OUT = os.path.join(APP, "covers")
WIDTH = 520
force = "--force" in sys.argv

src = open(os.path.join(APP, "books.js"), encoding="utf8").read()
books = json.loads(re.search(r"=\s*(\[.*\])\s*;?\s*$", src, re.S).group(1))
os.makedirs(OUT, exist_ok=True)

old = {}
cache = os.path.join(APP, "covers.js")
if os.path.exists(cache) and not force:
    m = re.search(r"=\s*(\{.*\})\s*;?\s*$", open(cache, encoding="utf8").read(), re.S)
    if m: old = json.loads(m.group(1))


def lum(rgb):
    r, g, b = (c / 255 for c in rgb)
    f = lambda c: c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)


def edge_colour(pix):
    # median of the left 8% strip, skipping the outermost pixels (scan borders)
    w, h, n = pix.width, pix.height, pix.n
    x0, x1 = max(1, int(w * 0.01)), max(2, int(w * 0.08))
    chans = [[], [], []]
    s = pix.samples
    for y in range(int(h * 0.05), int(h * 0.95), 3):
        for x in range(x0, x1, 2):
            i = (y * w + x) * n
            for c in range(3): chans[c].append(s[i + c])
    med = [sorted(c)[len(c) // 2] for c in chans]
    return med


def ink(pix):
    # share of clearly non-white pixels; near-empty title pages score very low
    s, n, dark, total = pix.samples, pix.n, 0, 0
    for i in range(0, len(s) - 2, n * 7):
        total += 1
        if s[i] + s[i + 1] + s[i + 2] < 600: dark += 1
    return round(dark / max(total, 1), 4)


def hexc(rgb): return "#%02x%02x%02x" % tuple(int(c) for c in rgb)


out, made, failed = {}, 0, []
for b in books:
    p = b["path"]
    if not p.lower().endswith(".pdf"): continue
    cid = hashlib.sha1(p.encode("utf8")).hexdigest()[:14]
    rel = f"covers/{cid}.jpg"
    if p in old and os.path.exists(os.path.join(APP, rel)):
        out[p] = old[p]; continue
    try:
        doc = fitz.open(p)
        page = doc[0]
        zoom = WIDTH / page.rect.width
        pix = page.get_pixmap(matrix=fitz.Matrix(zoom, zoom), colorspace=fitz.csRGB, alpha=False)
        pix.save(os.path.join(APP, rel), jpg_quality=82)
        bg = edge_colour(pix)
        # near-white pages read as paper; keep them warm off-white rather than stark white
        if lum(bg) > 0.85: bg = [236, 233, 226]
        fg = "#141414" if lum(bg) > 0.33 else "#f4f2ed"
        out[p] = {"f": rel, "ar": round(pix.width / pix.height, 4), "bg": hexc(bg), "fg": fg, "ink": ink(pix)}
        made += 1
        doc.close()
    except Exception as e:
        failed.append(f"{p}: {e}")

with open(cache, "w", encoding="utf8") as f:
    f.write("// GENERATED by scripts/make-covers.py. Do not hand-edit.\nwindow.COVERS = ")
    json.dump(out, f, indent=1, ensure_ascii=False)
    f.write(";\n")

# drop images for books that are gone
keep = {os.path.basename(v["f"]) for v in out.values()}
for n in os.listdir(OUT):
    if n not in keep: os.remove(os.path.join(OUT, n))

print(f"covers: {len(out)} ({made} new)")
for f in failed: print("  failed", f)
